-- Execute UMA VEZ como MEDISTOCK / FREEPDB1, usando F5.
-- Migracao incremental: preserva as seis tabelas e os dados da etapa anterior.
SET DEFINE OFF
SET SERVEROUTPUT ON
WHENEVER SQLERROR EXIT FAILURE ROLLBACK

DECLARE
    v_total NUMBER;
BEGIN
    IF SYS_CONTEXT('USERENV', 'SESSION_USER') <> 'MEDISTOCK'
       OR SYS_CONTEXT('USERENV', 'CON_NAME') <> 'FREEPDB1' THEN
        RAISE_APPLICATION_ERROR(-20090, 'Use MEDISTOCK no FREEPDB1.');
    END IF;
    SELECT COUNT(*) INTO v_total FROM USER_TABLES
    WHERE TABLE_NAME IN ('ITENS_ESTOQUE', 'HOSPITAIS', 'HISTORICO_CONSUMO');
    IF v_total <> 3 THEN
        RAISE_APPLICATION_ERROR(-20094, 'As tabelas da etapa anterior precisam existir neste schema.');
    END IF;
    SELECT COUNT(*) INTO v_total FROM USER_OBJECTS
    WHERE OBJECT_NAME = 'AUDITORIA_CONSUMO';
    IF v_total > 0 THEN
        RAISE_APPLICATION_ERROR(-20091,
            'AUDITORIA_CONSUMO ja existe. Nao apague seus logs; confira o script 11.');
    END IF;
END;
/

CREATE TABLE AUDITORIA_CONSUMO (
    ID NUMBER(19,0) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    HISTORICO_ID NUMBER(19,0) NOT NULL,
    OPERACAO VARCHAR2(6 CHAR) NOT NULL,
    ITEM_ID_ANTES NUMBER(19,0),
    ITEM_ID_DEPOIS NUMBER(19,0),
    HOSPITAL_ID_ANTES NUMBER(19,0),
    HOSPITAL_ID_DEPOIS NUMBER(19,0),
    REFERENCIA_ANTES DATE,
    REFERENCIA_DEPOIS DATE,
    QUANTIDADE_ANTES NUMBER(10,0),
    QUANTIDADE_DEPOIS NUMBER(10,0),
    USUARIO_BANCO VARCHAR2(128 CHAR) NOT NULL,
    CLIENT_IDENTIFIER VARCHAR2(64 CHAR),
    MODULO VARCHAR2(64 CHAR),
    REGISTRADO_EM TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_AUDITORIA_CONSUMO PRIMARY KEY (ID),
    CONSTRAINT CK_AUD_CONSUMO_OPERACAO CHECK (OPERACAO IN ('INSERT', 'UPDATE', 'DELETE'))
);

-- Sem FK para o historico: o registro de auditoria deve sobreviver ao DELETE.
CREATE INDEX IX_AUD_CONSUMO_HISTORICO ON AUDITORIA_CONSUMO (HISTORICO_ID, ID);

COMMENT ON TABLE AUDITORIA_CONSUMO IS 'Auditoria transacional das alteracoes futuras em HISTORICO_CONSUMO.';
COMMENT ON COLUMN AUDITORIA_CONSUMO.ID IS 'Identificador do evento, gerado por identidade Oracle.';
COMMENT ON COLUMN AUDITORIA_CONSUMO.HISTORICO_ID IS 'ID do historico afetado: novo em INSERT/UPDATE, antigo em DELETE; sem FK.';
COMMENT ON COLUMN AUDITORIA_CONSUMO.OPERACAO IS 'Operacao que originou o evento: INSERT, UPDATE ou DELETE.';
COMMENT ON COLUMN AUDITORIA_CONSUMO.ITEM_ID_ANTES IS 'Item antes da alteracao; NULL em INSERT.';
COMMENT ON COLUMN AUDITORIA_CONSUMO.ITEM_ID_DEPOIS IS 'Item depois da alteracao; NULL em DELETE.';
COMMENT ON COLUMN AUDITORIA_CONSUMO.HOSPITAL_ID_ANTES IS 'Hospital antes da alteracao; NULL em INSERT.';
COMMENT ON COLUMN AUDITORIA_CONSUMO.HOSPITAL_ID_DEPOIS IS 'Hospital depois da alteracao; NULL em DELETE.';
COMMENT ON COLUMN AUDITORIA_CONSUMO.REFERENCIA_ANTES IS 'Data de referencia anterior; NULL em INSERT.';
COMMENT ON COLUMN AUDITORIA_CONSUMO.REFERENCIA_DEPOIS IS 'Data de referencia posterior; NULL em DELETE.';
COMMENT ON COLUMN AUDITORIA_CONSUMO.QUANTIDADE_ANTES IS 'Quantidade anterior; NULL em INSERT.';
COMMENT ON COLUMN AUDITORIA_CONSUMO.QUANTIDADE_DEPOIS IS 'Quantidade posterior; NULL em DELETE.';
COMMENT ON COLUMN AUDITORIA_CONSUMO.USUARIO_BANCO IS 'SESSION_USER da conexao Oracle; nao identifica automaticamente o usuario JWT.';
COMMENT ON COLUMN AUDITORIA_CONSUMO.CLIENT_IDENTIFIER IS 'Identificador opcional definido pela aplicacao na sessao Oracle.';
COMMENT ON COLUMN AUDITORIA_CONSUMO.MODULO IS 'Modulo informado pela ferramenta ou pela aplicacao na sessao Oracle.';
COMMENT ON COLUMN AUDITORIA_CONSUMO.REGISTRADO_EM IS 'Data, hora e fuso do evento no banco.';

PROMPT Tabela e indice de auditoria criados. A captura inicia apos o script 10.
