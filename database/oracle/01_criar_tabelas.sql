CREATE TABLE USUARIOS (
    ID NUMBER(19,0) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    PRIMEIRO_NOME VARCHAR2(80 CHAR) NOT NULL,
    ULTIMO_NOME VARCHAR2(80 CHAR) NOT NULL,
    EMAIL_INSTITUCIONAL VARCHAR2(150 CHAR) NOT NULL,
    SENHA_HASH VARCHAR2(255 CHAR) NOT NULL,
    CRIADO_EM TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL,
    CONSTRAINT PK_USUARIOS PRIMARY KEY (ID),
    CONSTRAINT UK_USUARIO_EMAIL UNIQUE (EMAIL_INSTITUCIONAL)
);

COMMENT ON COLUMN USUARIOS.ID IS 'Chave primária; gerada pelo Oracle.';
COMMENT ON COLUMN USUARIOS.PRIMEIRO_NOME IS 'Primeiro nome do usuário.';
COMMENT ON COLUMN USUARIOS.ULTIMO_NOME IS 'Sobrenome do usuário.';
COMMENT ON COLUMN USUARIOS.EMAIL_INSTITUCIONAL IS 'E-mail institucional único; a API normaliza para minúsculas.';
COMMENT ON COLUMN USUARIOS.SENHA_HASH IS 'Hash BCrypt produzido pelo cadastro da API.';
COMMENT ON COLUMN USUARIOS.CRIADO_EM IS 'Data e hora de criação, sem fuso no modelo atual.';

CREATE TABLE HOSPITAIS (
