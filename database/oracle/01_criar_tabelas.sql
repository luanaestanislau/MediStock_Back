CREATE TABLE ITENS_ESTOQUE (
    ID NUMBER(19,0) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    NOME VARCHAR2(150 CHAR) NOT NULL,
    QUANTIDADE_ATUAL NUMBER(10,0) NOT NULL,
    QUANTIDADE_MINIMA NUMBER(10,0) NOT NULL,
    UNIDADE_MEDIDA VARCHAR2(20 CHAR),
    LOCAL_ARMAZENAMENTO VARCHAR2(150 CHAR),
    HOSPITAL_ID NUMBER(19,0) NOT NULL,
    VALIDADE DATE,
    CUSTO_UNITARIO NUMBER(12,2),
    ALTO_CUSTO_BAIXA_DEMANDA BOOLEAN DEFAULT FALSE NOT NULL,
    ATUALIZADO_EM TIMESTAMP(6) DEFAULT LOCALTIMESTAMP,
    CONSTRAINT PK_ITENS_ESTOQUE PRIMARY KEY (ID),
    CONSTRAINT CK_ITEM_ATUAL CHECK (QUANTIDADE_ATUAL >= 0),
    CONSTRAINT CK_ITEM_MINIMA CHECK (QUANTIDADE_MINIMA >= 0),
    CONSTRAINT CK_ITEM_CUSTO CHECK (CUSTO_UNITARIO >= 0),
    CONSTRAINT FK_ITEM_HOSPITAL FOREIGN KEY (HOSPITAL_ID) REFERENCES HOSPITAIS(ID)
);

COMMENT ON COLUMN ITENS_ESTOQUE.ID IS 'Chave primária; gerada pelo Oracle.';
COMMENT ON COLUMN ITENS_ESTOQUE.NOME IS 'Nome do insumo.';
COMMENT ON COLUMN ITENS_ESTOQUE.QUANTIDADE_ATUAL IS 'Saldo atual; não negativo.';
COMMENT ON COLUMN ITENS_ESTOQUE.QUANTIDADE_MINIMA IS 'Limite mínimo do estoque; não negativo.';
COMMENT ON COLUMN ITENS_ESTOQUE.UNIDADE_MEDIDA IS 'Unidade usada para as quantidades.';
COMMENT ON COLUMN ITENS_ESTOQUE.LOCAL_ARMAZENAMENTO IS 'Local do item dentro do hospital.';
COMMENT ON COLUMN ITENS_ESTOQUE.HOSPITAL_ID IS 'FK para HOSPITAIS.ID; local atual do item.';
COMMENT ON COLUMN ITENS_ESTOQUE.VALIDADE IS 'Data de validade.';
COMMENT ON COLUMN ITENS_ESTOQUE.CUSTO_UNITARIO IS 'Custo unitário; não negativo.';
COMMENT ON COLUMN ITENS_ESTOQUE.ALTO_CUSTO_BAIXA_DEMANDA IS 'Indica elegibilidade para análise de redistribuição.';
COMMENT ON COLUMN ITENS_ESTOQUE.ATUALIZADO_EM IS 'Última atualização; a API atualiza via @PreUpdate.';

CREATE TABLE HISTORICO_CONSUMO (
    ID NUMBER(19,0) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ITEM_ESTOQUE_ID NUMBER(19,0) NOT NULL,
    HOSPITAL_ID NUMBER(19,0) NOT NULL,
    MES_REFERENCIA DATE NOT NULL,
    QUANTIDADE_CONSUMIDA NUMBER(10,0) NOT NULL,
    CONSTRAINT PK_HISTORICO_CONSUMO PRIMARY KEY (ID),
    CONSTRAINT CK_HIST_QUANTIDADE CHECK (QUANTIDADE_CONSUMIDA >= 0),
    CONSTRAINT FK_HIST_ITEM FOREIGN KEY (ITEM_ESTOQUE_ID) REFERENCES ITENS_ESTOQUE(ID),
    CONSTRAINT FK_HIST_HOSPITAL FOREIGN KEY (HOSPITAL_ID) REFERENCES HOSPITAIS(ID)
);

COMMENT ON COLUMN HISTORICO_CONSUMO.ID IS 'Chave primária; gerada pelo Oracle.';
COMMENT ON COLUMN HISTORICO_CONSUMO.ITEM_ESTOQUE_ID IS 'FK para ITENS_ESTOQUE.ID.';
COMMENT ON COLUMN HISTORICO_CONSUMO.HOSPITAL_ID IS 'FK para HOSPITAIS.ID; hospital que registrou a demanda.';
COMMENT ON COLUMN HISTORICO_CONSUMO.MES_REFERENCIA IS 'Referência do consumo; a carga usa o primeiro dia do mês.';
COMMENT ON COLUMN HISTORICO_CONSUMO.QUANTIDADE_CONSUMIDA IS 'Quantidade consumida registrada; não negativa.';

CREATE TABLE ENTREGAS (
    ID NUMBER(19,0) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ITEM_ESTOQUE_ID NUMBER(19,0) NOT NULL,
    HOSPITAL_DESTINO_ID NUMBER(19,0) NOT NULL,
    QUANTIDADE NUMBER(10,0) NOT NULL,
    STATUS VARCHAR2(20 CHAR) DEFAULT 'PENDENTE' NOT NULL,
    DATA_PREVISTA DATE,
    TRANSPORTADORA VARCHAR2(150 CHAR),
    CRIADO_EM TIMESTAMP(6) DEFAULT LOCALTIMESTAMP,
    CONSTRAINT PK_ENTREGAS PRIMARY KEY (ID),
    CONSTRAINT CK_ENTREGA_STATUS CHECK (STATUS IN ('PENDENTE','EM_ROTA','CONCLUIDA','CANCELADA')),
    CONSTRAINT CK_ENTREGA_QUANTIDADE CHECK (QUANTIDADE > 0),
    CONSTRAINT FK_ENTREGA_ITEM FOREIGN KEY (ITEM_ESTOQUE_ID) REFERENCES ITENS_ESTOQUE(ID),
    CONSTRAINT FK_ENTREGA_DESTINO FOREIGN KEY (HOSPITAL_DESTINO_ID) REFERENCES HOSPITAIS(ID)
);

COMMENT ON COLUMN ENTREGAS.ID IS 'Chave primária; gerada pelo Oracle.';
COMMENT ON COLUMN ENTREGAS.ITEM_ESTOQUE_ID IS 'FK para ITENS_ESTOQUE.ID.';
COMMENT ON COLUMN ENTREGAS.HOSPITAL_DESTINO_ID IS 'FK para HOSPITAIS.ID.';
COMMENT ON COLUMN ENTREGAS.QUANTIDADE IS 'Quantidade da entrega; maior que zero.';
COMMENT ON COLUMN ENTREGAS.STATUS IS 'PENDENTE, EM_ROTA, CONCLUIDA ou CANCELADA.';
COMMENT ON COLUMN ENTREGAS.DATA_PREVISTA IS 'Data prevista para a entrega.';
COMMENT ON COLUMN ENTREGAS.TRANSPORTADORA IS 'Nome da transportadora.';
COMMENT ON COLUMN ENTREGAS.CRIADO_EM IS 'Data e hora de criação.';

CREATE TABLE TRANSFERENCIAS (
    ID NUMBER(19,0) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ITEM_ESTOQUE_ID NUMBER(19,0) NOT NULL,
    HOSPITAL_ORIGEM_ID NUMBER(19,0) NOT NULL,
    HOSPITAL_DESTINO_ID NUMBER(19,0) NOT NULL,
    QUANTIDADE NUMBER(10,0) NOT NULL,
