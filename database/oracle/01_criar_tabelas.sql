    GERADO_POR_IA BOOLEAN DEFAULT FALSE NOT NULL,
    CRIADO_EM TIMESTAMP(6) DEFAULT LOCALTIMESTAMP,
    CONSTRAINT PK_TRANSFERENCIAS PRIMARY KEY (ID),
    CONSTRAINT CK_TRANSF_STATUS CHECK (STATUS IN ('PENDENTE','EM_ROTA','CONCLUIDA','CANCELADA')),
    CONSTRAINT CK_TRANSF_QUANTIDADE CHECK (QUANTIDADE > 0),
    CONSTRAINT FK_TRANSF_ITEM FOREIGN KEY (ITEM_ESTOQUE_ID) REFERENCES ITENS_ESTOQUE(ID),
    CONSTRAINT FK_TRANSF_ORIGEM FOREIGN KEY (HOSPITAL_ORIGEM_ID) REFERENCES HOSPITAIS(ID),
    CONSTRAINT FK_TRANSF_DESTINO FOREIGN KEY (HOSPITAL_DESTINO_ID) REFERENCES HOSPITAIS(ID)
);

COMMENT ON COLUMN TRANSFERENCIAS.ID IS 'Chave primária; gerada pelo Oracle.';
COMMENT ON COLUMN TRANSFERENCIAS.ITEM_ESTOQUE_ID IS 'FK para ITENS_ESTOQUE.ID.';
COMMENT ON COLUMN TRANSFERENCIAS.HOSPITAL_ORIGEM_ID IS 'FK para HOSPITAIS.ID; origem.';
COMMENT ON COLUMN TRANSFERENCIAS.HOSPITAL_DESTINO_ID IS 'FK para HOSPITAIS.ID; destino.';
COMMENT ON COLUMN TRANSFERENCIAS.QUANTIDADE IS 'Quantidade a transferir; maior que zero.';
COMMENT ON COLUMN TRANSFERENCIAS.STATUS IS 'PENDENTE, EM_ROTA, CONCLUIDA ou CANCELADA.';
COMMENT ON COLUMN TRANSFERENCIAS.DISTANCIA_KM IS 'Distância estimada em quilômetros.';
COMMENT ON COLUMN TRANSFERENCIAS.TEMPO_ESTIMADO_MIN IS 'Tempo estimado em minutos.';
COMMENT ON COLUMN TRANSFERENCIAS.MOTIVO IS 'Justificativa da transferência.';
COMMENT ON COLUMN TRANSFERENCIAS.GERADO_POR_IA IS 'Indica se a origem do registro foi uma sugestão de IA.';
