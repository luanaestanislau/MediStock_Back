-- Execute como MEDISTOCK / FREEPDB1 com F5, apos 06 a 10.
SET DEFINE OFF
SET SERVEROUTPUT ON
WHENEVER SQLERROR EXIT FAILURE ROLLBACK

BEGIN
    IF SYS_CONTEXT('USERENV', 'SESSION_USER') <> 'MEDISTOCK'
       OR SYS_CONTEXT('USERENV', 'CON_NAME') <> 'FREEPDB1' THEN
        RAISE_APPLICATION_ERROR(-20090, 'Use MEDISTOCK no FREEPDB1.');
    END IF;
END;
/

SELECT USER AS USUARIO, SYS_CONTEXT('USERENV', 'CON_NAME') AS CONTAINER FROM DUAL;

PROMPT Esperado: seis objetos abaixo, todos VALID.
SELECT OBJECT_NAME, OBJECT_TYPE, STATUS
FROM USER_OBJECTS
WHERE OBJECT_NAME IN ('AUDITORIA_CONSUMO', 'IX_AUD_CONSUMO_HISTORICO',
                      'PKG_MEDISTOCK', 'PR_REGISTRAR_CONSUMO', 'TRG_AUD_HISTORICO_CONSUMO')
ORDER BY OBJECT_TYPE, OBJECT_NAME;

PROMPT Esperado: trigger ENABLED, na tabela HISTORICO_CONSUMO.
SELECT TRIGGER_NAME, TABLE_NAME, TRIGGER_TYPE, TRIGGERING_EVENT, STATUS
FROM USER_TRIGGERS WHERE TRIGGER_NAME = 'TRG_AUD_HISTORICO_CONSUMO';

PROMPT Esperado: nenhuma linha de erro de compilacao.
SELECT NAME, TYPE, LINE, POSITION, TEXT
FROM USER_ERRORS
WHERE NAME IN ('PKG_MEDISTOCK', 'PR_REGISTRAR_CONSUMO', 'TRG_AUD_HISTORICO_CONSUMO')
  AND ATTRIBUTE = 'ERROR'
ORDER BY NAME, TYPE, SEQUENCE;

PROMPT Esperado: procedure antiga depende do package novo.
SELECT NAME, TYPE, REFERENCED_NAME, REFERENCED_TYPE
FROM USER_DEPENDENCIES
WHERE NAME = 'PR_REGISTRAR_CONSUMO' AND REFERENCED_NAME = 'PKG_MEDISTOCK';

PROMPT Estrutura da nova tabela: quinze colunas.
SELECT COLUMN_ID, COLUMN_NAME, DATA_TYPE, DATA_PRECISION, DATA_SCALE, CHAR_LENGTH, NULLABLE
FROM USER_TAB_COLUMNS WHERE TABLE_NAME = 'AUDITORIA_CONSUMO' ORDER BY COLUMN_ID;

DECLARE
    v_validos NUMBER;
    v_erros NUMBER;
    v_habilitadas NUMBER;
    v_dependencias NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_validos FROM USER_OBJECTS
    WHERE STATUS = 'VALID' AND (
        (OBJECT_NAME = 'AUDITORIA_CONSUMO' AND OBJECT_TYPE = 'TABLE') OR
        (OBJECT_NAME = 'IX_AUD_CONSUMO_HISTORICO' AND OBJECT_TYPE = 'INDEX') OR
        (OBJECT_NAME = 'PKG_MEDISTOCK' AND OBJECT_TYPE IN ('PACKAGE', 'PACKAGE BODY')) OR
        (OBJECT_NAME = 'PR_REGISTRAR_CONSUMO' AND OBJECT_TYPE = 'PROCEDURE') OR
        (OBJECT_NAME = 'TRG_AUD_HISTORICO_CONSUMO' AND OBJECT_TYPE = 'TRIGGER'));
    SELECT COUNT(*) INTO v_erros FROM USER_ERRORS
    WHERE NAME IN ('PKG_MEDISTOCK', 'PR_REGISTRAR_CONSUMO', 'TRG_AUD_HISTORICO_CONSUMO')
      AND ATTRIBUTE = 'ERROR';
    SELECT COUNT(*) INTO v_habilitadas FROM USER_TRIGGERS
    WHERE TRIGGER_NAME = 'TRG_AUD_HISTORICO_CONSUMO' AND STATUS = 'ENABLED';
    SELECT COUNT(*) INTO v_dependencias FROM USER_DEPENDENCIES
    WHERE NAME = 'PR_REGISTRAR_CONSUMO' AND TYPE = 'PROCEDURE'
      AND REFERENCED_NAME = 'PKG_MEDISTOCK' AND REFERENCED_TYPE = 'PACKAGE';
    IF v_validos <> 6 OR v_erros <> 0 OR v_habilitadas <> 1 OR v_dependencias <> 1 THEN
        RAISE_APPLICATION_ERROR(-20093, 'Validacao falhou. Examine os resultados acima antes de continuar.');
    END IF;
    DBMS_OUTPUT.PUT_LINE('OK: objetos VALID, trigger ENABLED e procedure adaptadora ligada ao package.');
END;
/
