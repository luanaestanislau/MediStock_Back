-- Execute como SYSTEM / FREEPDB1, usando F5 no SQL Developer.
-- Complementa as permissoes da etapa anterior. Pode ser reexecutado.
SET DEFINE OFF
SET SERVEROUTPUT ON
WHENEVER SQLERROR EXIT FAILURE ROLLBACK

BEGIN
    IF SYS_CONTEXT('USERENV', 'SESSION_USER') <> 'SYSTEM'
       OR SYS_CONTEXT('USERENV', 'CON_NAME') <> 'FREEPDB1' THEN
        RAISE_APPLICATION_ERROR(-20090, 'Use SYSTEM no FREEPDB1 para este arquivo.');
    END IF;
END;
/

GRANT CREATE TRIGGER TO MEDISTOCK;

SELECT GRANTEE, PRIVILEGE
FROM DBA_SYS_PRIVS
WHERE GRANTEE = 'MEDISTOCK' AND PRIVILEGE = 'CREATE TRIGGER';

PROMPT Permissao concedida. Execute os proximos arquivos como MEDISTOCK / FREEPDB1.
