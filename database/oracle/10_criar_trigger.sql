-- Execute como MEDISTOCK / FREEPDB1, usando F5, apos 07 a 09.
SET DEFINE OFF
SET SERVEROUTPUT ON
WHENEVER SQLERROR EXIT FAILURE ROLLBACK

BEGIN
    IF SYS_CONTEXT('USERENV', 'SESSION_USER') <> 'MEDISTOCK'
       OR SYS_CONTEXT('USERENV', 'CON_NAME') <> 'FREEPDB1' THEN
        RAISE_APPLICATION_ERROR(-20090, 'Use MEDISTOCK no FREEPDB1.');
    END IF;
END;
/

CREATE OR REPLACE TRIGGER TRG_AUD_HISTORICO_CONSUMO
AFTER INSERT OR UPDATE OR DELETE ON HISTORICO_CONSUMO
FOR EACH ROW
DECLARE
    v_operacao VARCHAR2(6);
BEGIN
    IF INSERTING THEN
        v_operacao := 'INSERT';
    ELSIF UPDATING THEN
        v_operacao := 'UPDATE';
    ELSE
        v_operacao := 'DELETE';
    END IF;

    INSERT INTO AUDITORIA_CONSUMO (
        HISTORICO_ID, OPERACAO,
        ITEM_ID_ANTES, ITEM_ID_DEPOIS,
        HOSPITAL_ID_ANTES, HOSPITAL_ID_DEPOIS,
        REFERENCIA_ANTES, REFERENCIA_DEPOIS,
        QUANTIDADE_ANTES, QUANTIDADE_DEPOIS,
        USUARIO_BANCO, CLIENT_IDENTIFIER, MODULO
    ) VALUES (
        NVL(:NEW.ID, :OLD.ID), v_operacao,
        :OLD.ITEM_ESTOQUE_ID, :NEW.ITEM_ESTOQUE_ID,
        :OLD.HOSPITAL_ID, :NEW.HOSPITAL_ID,
        :OLD.MES_REFERENCIA, :NEW.MES_REFERENCIA,
        :OLD.QUANTIDADE_CONSUMIDA, :NEW.QUANTIDADE_CONSUMIDA,
        SYS_CONTEXT('USERENV', 'SESSION_USER'),
        SYS_CONTEXT('USERENV', 'CLIENT_IDENTIFIER'),
        SYS_CONTEXT('USERENV', 'MODULE')
    );
    -- Sem COMMIT, ROLLBACK ou transacao autonoma: log acompanha a transacao.
END TRG_AUD_HISTORICO_CONSUMO;
/
SHOW ERRORS TRIGGER TRG_AUD_HISTORICO_CONSUMO

DECLARE
    v_validos NUMBER;
    v_habilitada NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_validos FROM USER_OBJECTS
    WHERE OBJECT_NAME = 'TRG_AUD_HISTORICO_CONSUMO'
      AND OBJECT_TYPE = 'TRIGGER' AND STATUS = 'VALID';
    SELECT COUNT(*) INTO v_habilitada FROM USER_TRIGGERS
    WHERE TRIGGER_NAME = 'TRG_AUD_HISTORICO_CONSUMO' AND STATUS = 'ENABLED';
    IF v_validos <> 1 OR v_habilitada <> 1 THEN
        RAISE_APPLICATION_ERROR(-20093, 'Trigger invalida ou desabilitada. Consulte USER_ERRORS e USER_TRIGGERS.');
    END IF;
    DBMS_OUTPUT.PUT_LINE('OK: trigger VALID e ENABLED. Novas operacoes geram auditoria.');
END;
/
