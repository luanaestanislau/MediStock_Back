PROMPT 2. Contagens para comparar antes/depois de um unico POST.
SELECT (SELECT COUNT(*) FROM HISTORICO_CONSUMO) AS TOTAL_HISTORICOS,
       (SELECT COUNT(*) FROM AUDITORIA_CONSUMO) AS TOTAL_EVENTOS
